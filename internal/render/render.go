// Package render turns accounts into file contents, and does nothing else.
//
// Pure functions: in go accounts and the program config, out come strings. No I/O at all, which is
// what makes the whole set golden-testable — the samples in the plan are frozen as fixtures, and a
// change to any generated line has to be a change somebody meant to make.
//
// The ownership line this package sits on: render is the only place that knows what the files SAY.
// If a rendered file is wrong, the bug is here and nowhere else.
package render

import (
	"fmt"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"unicode/utf8"

	"github.com/lvim-tech/mailforge/internal/account"
	"github.com/lvim-tech/mailforge/internal/config"
)

// Header marks every file mailforge owns whole.
//
// It says "regenerated", not "do not edit", because the first is a fact and the second is a wish:
// the reason not to edit is that the next apply overwrites it, and saying so is what makes the
// warning believable.
var Header = header("accounts.json")

// HeaderFromConfig marks the files rendered from config.json rather than from the accounts.
// Naming the wrong source is worse than naming none: somebody edits accounts.json looking for a
// setting that is not in it.
var HeaderFromConfig = header("config.json")

func header(src string) string {
	return "# Generated by mailforge — do not edit by hand.\n" +
		"# This file is rewritten from ~/.config/mailforge/" + src + " on every apply.\n"
}

// AccountRC is the per-account neomutt file, owned whole.
//
// The password comes from a backtick command rather than being written here: the file is plain
// text on disk, and a password in it would undo the point of having a password store at all. The
// cost is that `pass show` runs on every folder-hook switch — milliseconds against a warm
// gpg-agent, and one prompt per agent lifetime at worst. That is the standard NeoMutt/pass
// integration and the trade is deliberate.
func AccountRC(c config.Config, a account.Account) string {
	var b strings.Builder
	b.WriteString(Header)
	b.WriteString("\n")

	set := func(k, v string) { fmt.Fprintf(&b, "set %-22s = %s\n", k, v) }

	if a.RealName != "" {
		set("realname", quote(a.RealName))
	}
	set("from", quote(a.Address))
	set("folder", quote(a.Maildir(c)))
	set("spoolfile", quote("+INBOX"))

	// LOCAL names, not the server's. NeoMutt reads the maildir mbsync wrote, and mbsync stores
	// what the server calls "INBOX.Sent" in a directory called "Sent".
	local := a.LocalFolders()

	// record is where NeoMutt files a copy of what you send. Gmail does that server-side, so
	// setting it there gives every sent message twice — one from the server, one from us.
	if a.Quirks.NoRecord {
		b.WriteString("unset record   # the server files sent mail itself; a copy here would duplicate it\n")
	} else if local.Sent != "" {
		set("record", quote("+"+local.Sent))
	}
	if local.Drafts != "" {
		set("postponed", quote("+"+local.Drafts))
	}
	if local.Trash != "" {
		set("trash", quote("+"+local.Trash))
	}

	// The signature, appended to everything sent from this account. Written as a PATH rather
	// than inlined: NeoMutt reads the file at send time, so editing it takes effect on the next
	// message instead of on the next apply. `unset` when there is none, because leaving the
	// previous account's value standing would sign this one with somebody else's name — the
	// account files are sourced by a folder-hook, and what one sets the next does not clear.
	if strings.TrimSpace(a.Signature) != "" {
		set("signature", quote(a.SigFile(c)))
	} else {
		b.WriteString("unset signature\n")
	}

	b.WriteString("\n")
	set("smtp_url", quote(a.SMTPURL()))
	set("smtp_pass", "\"`pass show "+shellQuote(a.PassEntry(c))+" | head -1`\"")
	// head -1: a pass entry may carry metadata under the password, and NeoMutt would take the
	// whole output as the passphrase. One line is the password by pass's own convention.
	set("smtp_authenticators", quote("plain:login"))

	// WHICH ACCOUNT IS BEING READ, written down for the fold key and for nothing else.
	//
	// The folder-hook sources this file on every change of folder, and NeoMutt runs a backtick
	// each time it parses the line — so this command runs then, which is the only moment
	// anything outside NeoMutt can learn which account is open. Enter's macro is ONE fixed
	// string shared by every account: without this it would have no way to name the account it
	// is being asked to fold.
	//
	// The value is thrown away. A my_ variable is simply the only place a muttrc can put the
	// output of a command it runs for the effect, and this command prints nothing.
	if c.SidebarCollapse {
		b.WriteString("\n")
		set("my_mailforge_sidebar", "`mailforge sidebar current "+shellQuote(a.Address)+"`")
	}
	return b.String()
}

// AccountsRC is the index: the sidebar, the folder hooks, and which account owns startup.
func AccountsRC(c config.Config, accounts []account.Account) string {
	var b strings.Builder
	b.WriteString(Header)

	sorted := append([]account.Account(nil), accounts...)
	sort.SliceStable(sorted, func(i, j int) bool { return sorted[i].Order < sorted[j].Order })

	// Folded, the mailbox list is not in this file at all: it changes on a keypress, and this
	// file is rewritten only by an apply. Two owners for one list would mean the next apply
	// quietly unfolding whatever the user had folded open.
	if c.SidebarCollapse {
		b.WriteString("\n# The sidebar is folded, so the mailbox list lives in its own file:\n")
		b.WriteString("# it is rewritten on every fold, and this one is not.\n")
		fmt.Fprintf(&b, "source %s\n", SidebarPath(c))
	}

	for _, a := range sorted {
		b.WriteString("\n")
		// ABSOLUTE paths, not the "=" shorthand.
		//
		// "=" expands against $folder AT PARSE TIME, and when this file is read $folder is
		// still the default — the account rc that sets it is sourced afterwards. So every
		// mailbox registered with "=" pointed into ~/Mail, and the sidebar came up empty
		// while the maildirs sat elsewhere, correct and unreferenced.
		if !c.SidebarCollapse {
			dir := a.Maildir(c)
			fmt.Fprintf(&b, "named-mailboxes %s %s\n", quote(a.LabelOrDefault()), quote(dir+"/INBOX"))
			if boxes := mailboxLine(c, a); boxes != "" {
				b.WriteString(boxes + "\n")
			}
		}
		// The pattern is quoted: unquoted, an address containing a space would be read as a
		// pattern and a command rather than as one pattern.
		fmt.Fprintf(&b, "folder-hook %s source %s\n", quote(a.Address+"/*"), a.RCFile(c))
	}

	// AFTER every per-account hook, and the order is the whole mechanism.
	//
	// Both hooks match when an INBOX is opened, and NeoMutt runs them in the order they were
	// defined. The account's own hook assumes a plain folder; this one, running last, corrects
	// that to "an account's own row". Defined before them it would be overwritten by the very
	// hook it is meant to refine, and Enter would never fold anything.
	if c.SidebarCollapse {
		b.WriteString("\n# Last, so it has the final say when an INBOX is opened: it is what lets\n")
		b.WriteString("# Enter tell an account's own row from a folder underneath it.\n")
		fmt.Fprintf(&b, "folder-hook %s source %s\n", quote("/INBOX$"), InboxHookPath(c))
	}

	// Sourced last so its identity is the one in force at startup. A folder-hook fires on the
	// first folder change; without this the very first message composed after opening would go
	// out as whichever account NeoMutt happened to read last.
	if d, ok := defaultOf(sorted); ok {
		b.WriteString("\n# The default account, sourced last so its identity is the one at startup.\n")
		fmt.Fprintf(&b, "source %s\n", d.RCFile(c))
	}
	return b.String()
}

// FolderNames is the account's other mailboxes, in the order the sidebar shows them. Discovered
// names, not a hardcoded litany — that is the whole reason Folders is a discovered field.
//
// Exported because whoever counts the mail has to count the same mailboxes this file registers, and
// a second list of folder names kept in step by hand is the drift this program exists to prevent.
func FolderNames(a account.Account) []string {
	var out []string
	local := a.LocalFolders()
	for _, f := range []string{local.Sent, local.Drafts, local.Trash, local.Archive, local.Spam} {
		if f != "" {
			out = append(out, f)
		}
	}
	return out
}

// mailboxLine lists those mailboxes as one registration line, for the unfolded sidebar.
func mailboxLine(c config.Config, a account.Account) string {
	var boxes []string
	dir := a.Maildir(c)
	for _, f := range FolderNames(a) {
		boxes = append(boxes, quote(dir+"/"+f))
	}
	if len(boxes) == 0 {
		return ""
	}
	return "mailboxes " + strings.Join(boxes, " ")
}

func defaultOf(accounts []account.Account) (account.Account, bool) {
	for _, a := range accounts {
		if a.Default {
			return a, true
		}
	}
	if len(accounts) > 0 {
		return accounts[0], true
	}
	return account.Account{}, false
}

// MbsyncBlock is what goes between one account's markers in ~/.mbsyncrc.
//
// TLSType, not SSLType: isync 1.5 renamed it, and the old spelling prints
// "notice: SSLType is deprecated" today and will stop working later. Measured on this machine
// rather than taken from documentation.
//
// AuthMechs is left out entirely unless an account needs one. Pinning LOGIN — as the old
// hand-written file did — disables every better mechanism the server offers, permanently and
// invisibly.
func MbsyncBlock(c config.Config, a account.Account) string {
	var b strings.Builder

	fmt.Fprintf(&b, "IMAPStore %s\n", a.FarStore())
	fmt.Fprintf(&b, "Host %s\n", a.IMAP.Host)
	fmt.Fprintf(&b, "Port %d\n", a.IMAP.Port)
	fmt.Fprintf(&b, "User %s\n", a.IMAP.User(a.Address))
	fmt.Fprintf(&b, "PassCmd \"pass show %s | head -1\"\n", shellQuote(a.PassEntry(c)))
	fmt.Fprintf(&b, "TLSType %s\n", tlsType(a.IMAP.Security))
	fmt.Fprintf(&b, "CertificateFile %s\n", c.CertFile)
	b.WriteString("\n")

	dir := a.Maildir(c)
	fmt.Fprintf(&b, "MaildirStore %s\n", a.NearStore())
	b.WriteString("Subfolders Verbatim\n")
	fmt.Fprintf(&b, "Path %s/\n", dir)
	fmt.Fprintf(&b, "Inbox %s/INBOX\n", dir)
	b.WriteString("\n")

	fmt.Fprintf(&b, "Channel %s\n", a.Channel())
	fmt.Fprintf(&b, "Far :%s:\n", a.FarStore())
	fmt.Fprintf(&b, "Near :%s:\n", a.NearStore())
	fmt.Fprintf(&b, "Patterns %s\n", patterns(a))
	fmt.Fprintf(&b, "Create %s\n", c.Sync.Create)
	fmt.Fprintf(&b, "Expunge %s\n", c.Sync.Expunge)
	b.WriteString("SyncState *\n")
	if c.Sync.MaxMessages > 0 {
		fmt.Fprintf(&b, "MaxMessages %d\n", c.Sync.MaxMessages)
		fmt.Fprintf(&b, "ExpireUnread %s\n", yesno(c.Sync.ExpireUnread))
	}
	return b.String()
}

// patterns is what mbsync fetches. Gmail's All Mail is every message a second time, so an account
// that says so excludes it — a doubled maildir for no benefit is the alternative.
func patterns(a account.Account) string {
	if len(a.Quirks.SyncExclude) == 0 {
		return "*"
	}
	out := []string{"*"}
	for _, ex := range a.Quirks.SyncExclude {
		out = append(out, "!"+quote(ex))
	}
	return strings.Join(out, " ")
}

func tlsType(s account.Security) string {
	if s == account.STARTTLS {
		return "STARTTLS"
	}
	return "IMAPS"
}

func yesno(b bool) string {
	if b {
		return "yes"
	}
	return "no"
}

// NeomuttInclude is the accounts line mailforge keeps inside the user's own neomuttrc.
//
// Its block belongs LAST in that file. accounts.rc ends by sourcing the default account, which
// sets folder, from, record and the rest of the identity; anything sourced after it could override
// those, and a `set folder` added to settings.rc one day would break every mailbox path silently.
func NeomuttInclude(c config.Config) string {
	return fmt.Sprintf("source %s/mailforge/accounts.rc\n", c.NeomuttDir)
}

// NeomuttKeysInclude is the keys line, and its block belongs FIRST.
//
// The reason is the exact mirror of the one above. NeoMutt keeps the LAST binding it reads for a
// key, so whatever is sourced later wins — and for bindings the one that should win is the user's
// own bindings.rc, not this program's. Two blocks in two places, each positioned by what has to
// take precedence: identity last, keys first.
func NeomuttKeysInclude(c config.Config) string {
	return fmt.Sprintf("source %s/mailforge/keys.rc\n", c.NeomuttDir)
}

// quote wraps a value the way muttrc wants it, escaping what would end the string early.
//
// A display name with a quote in it is rare and a path with one is rarer, but the failure when it
// happens is a config file that stops parsing halfway with an error naming a line the user never
// wrote.
//
// BACKTICKS ARE ESCAPED TOO, and that one is not cosmetic: NeoMutt runs backticked text through the
// shell inside a double-quoted value — this very file depends on it for smtp_pass — so an
// unescaped backtick in a real name is a command that runs on every NeoMutt start. Newlines are
// replaced rather than escaped, because a value that spans lines ends the string whatever is done
// to it, and the rest of the line would be read as configuration.
func quote(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, "`", "\\`", "\n", " ", "\r", " ")
	return `"` + r.Replace(s) + `"`
}

// shellQuote wraps a value for /bin/sh, which is what NeoMutt's backticks and mbsync's PassCmd hand
// their command lines to. The pass entry is built from the address and the configured prefix, and
// neither is this program's own text.
func shellQuote(s string) string {
	return `'` + strings.ReplaceAll(s, `'`, `'\''`) + `'`
}

// SidebarPath is the generated sidebar file. One definition, because three packages need it: render
// writes it, apply puts it down and takes it away, and audit checks it is there.
func SidebarPath(c config.Config) string {
	return filepath.Join(c.NeomuttDir, "mailforge", "sidebar.rc")
}

/*
SidebarRC is the folded sidebar: one line per account, and the folders of the accounts that are
open.

It is a file of its own, and the only generated file rewritten OUTSIDE an apply — `mailforge
sidebar toggle` writes it on a keypress and NeoMutt sources it again, which is what makes folding
feel immediate. That is also why the whole list is rewritten rather than the one account that
changed: NeoMutt has no way to add or drop a single mailbox, only `unmailboxes *` and a fresh list,
so a partial update is not a smaller version of this — it is a different sidebar.

Why a count per account and not per folder: twelve accounts of six folders is eighty-four lines in
a thirty-two column strip, which is a list nobody reads. Folded, the account's own line carries %N
from sidebar_format, so the number that matters stays visible while the rest goes away.

What it CANNOT do is add up: the folded line counts that account's INBOX and nothing else, because
NeoMutt computes per mailbox and has no notion of a group. New mail arrives in INBOX, so the number
is right where it is looked at — but it is not a total, and Sent or Archive moving under a fold take
their counts with them.
*/
func SidebarRC(c config.Config, accounts []account.Account, expanded map[string]bool, highlight string, counts map[string]SidebarCount) string {
	var b strings.Builder
	b.WriteString(Header)
	b.WriteString("# Rewritten again, outside any apply, by `mailforge sidebar toggle`.\n")
	b.WriteString("#\n")
	b.WriteString("# Which accounts are folded open is remembered in " + config.StatePath() + ".\n")
	b.WriteString("\n")

	// EVERY mailbox goes first, so what is left is exactly this file and not this file plus
	// whatever the last one registered. Sourced at startup it clears nothing, which is why it is
	// safe in both roles.
	b.WriteString("unmailboxes *\n")

	sorted := append([]account.Account(nil), accounts...)
	sort.SliceStable(sorted, func(i, j int) bool { return sorted[i].Order < sorted[j].Order })

	rows := SidebarRows(c, sorted, expanded, counts)
	for _, r := range rows {
		fmt.Fprintf(&b, "named-mailboxes %s %s\n", quote(r.Label), quote(r.Path))
	}

	// The push is a number of steps down the list, so it is counted off the rows that were just
	// written rather than worked out again: an account's row sits after the folders of every
	// unfolded account above it.
	want := 0
	for i, r := range rows {
		if r.Address == highlight && r.IsAccount {
			want = i + 1
			break
		}
	}
	b.WriteString(sidebarHighlight(want))
	return b.String()
}

// SidebarCount is what one row's numbers are. Elsewhere is filled for account rows only.
type SidebarCount struct {
	// Total is every message in this mailbox.
	Total int
	// Unread is what has not been read in this mailbox.
	Unread int
	// Elsewhere is unread mail in the REST of the account — every maildir of it except INBOX,
	// spam and anything the server named itself included. It is the number NeoMutt cannot
	// produce: its own expandos are per mailbox and it has no notion of a group.
	Elsewhere int
}

// SidebarRow is one line of the sidebar, label and all.
type SidebarRow struct {
	Label   string
	Path    string
	Address string
	// IsAccount separates an account's own row — which is its INBOX — from a folder under it.
	IsAccount bool
}

/*
SidebarRows is the sidebar as text: one row per registered mailbox, numbers included.

THE NUMBERS ARE IN THE LABEL, and that is the whole reason this function exists. NeoMutt's
sidebar_format can only print what it knows about one mailbox, so "16[1/3]" — sixteen messages, one
unread here, three unread elsewhere in this account — is not something it can be asked for. Written
into the label it is just text, and the label is ours.

The price is that every number on the row has to come from here, including the ones NeoMutt would
have been happy to print: with a count in the label AND %S in the format, each row would carry two
sets of figures. So options.rc sets sidebar_format to %D alone when folding is on, and the padding
below is what right-aligns the numbers that NeoMutt's %* used to.

Folders are registered with named-mailboxes rather than mailboxes for the same reason: a label is
the only place a number can go. Two spaces of indent, which also replaces what sidebar_short_path
was doing — the label is no longer a path, so there is nothing left to shorten.
*/
func SidebarRows(c config.Config, accounts []account.Account, expanded map[string]bool, counts map[string]SidebarCount) []SidebarRow {
	var out []SidebarRow
	for _, a := range accounts {
		dir := a.Maildir(c)
		path := dir + "/INBOX"
		n := counts[path]
		out = append(out, SidebarRow{
			Label:     sidebarLabel(c.SidebarWidth, a.LabelOrDefault(), accountFigure(n)),
			Path:      path,
			Address:   a.Address,
			IsAccount: true,
		})
		if !expanded[a.Address] {
			continue
		}
		for _, f := range FolderNames(a) {
			p := dir + "/" + f
			fn := counts[p]
			out = append(out, SidebarRow{
				Label:   sidebarLabel(c.SidebarWidth, "  "+f, folderFigure(fn)),
				Path:    p,
				Address: a.Address,
			})
		}
	}
	return out
}

// accountFigure is "16" with nothing unread, "16[1/3]" with one unread here and three elsewhere.
//
// The brackets appear only when something is unread, because a column of [0/0] beside every account
// is noise that makes the one row that matters harder to find.
func accountFigure(n SidebarCount) string {
	if n.Unread == 0 && n.Elsewhere == 0 {
		return strconv.Itoa(n.Total)
	}
	return fmt.Sprintf("%d[%d/%d]", n.Total, n.Unread, n.Elsewhere)
}

// folderFigure is the same for a folder, which has no elsewhere of its own.
func folderFigure(n SidebarCount) string {
	if n.Unread == 0 {
		return strconv.Itoa(n.Total)
	}
	return fmt.Sprintf("%d[%d]", n.Total, n.Unread)
}

// sidebarLabel pads the text so the figure sits at the right edge of the sidebar.
//
// One column short of the width: the last one is NeoMutt's divider, and a label that reaches it has
// its final character eaten. At least one space always, so a label too long to fit is truncated by
// NeoMutt with its number still attached rather than running into it.
func sidebarLabel(width int, text, figure string) string {
	pad := width - 1 - utf8.RuneCountInString(text) - utf8.RuneCountInString(figure)
	if pad < 1 {
		pad = 1
	}
	return text + strings.Repeat(" ", pad) + figure
}

/*
CountsRC is the same rows WITHOUT the registration ritual: labels only.

It exists because of what a label change does and does not cost. `named-mailboxes` on a path that is
already registered UPDATES that row in place — measured in a running client: the label changed, no
row was duplicated, the order held, the view did not scroll and the highlight stayed where the user
had left it. Sourced from a timeout-hook every few seconds, that is a live count.

What must NOT be in this file is `unmailboxes *`, and the reason is the same measurement from the
other side: registering the list afresh scrolls the open mailbox to the top of the sidebar. A
refresh that did that every five seconds would fight the user for the scroll position and win.

The row SET has to match sidebar.rc exactly, which is why this takes the same expanded map. A row
named here that is not registered there would be ADDED by the refresh — folders of a folded account
appearing at the bottom of the list, which is what happened the first time this was tried.
*/
func CountsRC(c config.Config, accounts []account.Account, expanded map[string]bool, counts map[string]SidebarCount) string {
	var b strings.Builder
	b.WriteString(Header)
	b.WriteString("# Rewritten by `mailforge sidebar counts`, which the timeout-hook runs.\n")
	b.WriteString("#\n")
	b.WriteString("# Labels only, and deliberately no `unmailboxes`: re-registering the list would\n")
	b.WriteString("# scroll the open mailbox to the top every time this is read.\n\n")

	sorted := append([]account.Account(nil), accounts...)
	sort.SliceStable(sorted, func(i, j int) bool { return sorted[i].Order < sorted[j].Order })
	for _, r := range SidebarRows(c, sorted, expanded, counts) {
		fmt.Fprintf(&b, "named-mailboxes %s %s\n", quote(r.Label), quote(r.Path))
	}
	return b.String()
}

// CountsPath is the file CountsRC is written to.
func CountsPath(c config.Config) string {
	return filepath.Join(c.NeomuttDir, "mailforge", "counts.rc")
}

// RefreshPath is the file the timeout-hook sources.
func RefreshPath(c config.Config) string {
	return filepath.Join(c.NeomuttDir, "mailforge", "refresh.rc")
}

/*
RefreshRC is two lines, and it is the only way NeoMutt can be made to ask a question periodically.

A timeout-hook runs a muttrc COMMAND, and a backtick in a hook's command is expanded when the hook
line is parsed rather than when it fires — measured, so a hook that counted mail would have counted
it once at startup and never again. A hook that SOURCES A FILE re-reads that file every time it
fires, and a backtick inside the file is evaluated then. So the counting goes in a file.

The first line runs the program for its effect and throws the value away; the second reads what it
just wrote.
*/
func RefreshRC(c config.Config) string {
	var b strings.Builder
	b.WriteString(HeaderFromConfig)
	b.WriteString("#\n")
	b.WriteString("# Sourced by a timeout-hook, which NeoMutt runs when $timeout passes with no\n")
	b.WriteString("# keypress. The backtick recounts the mail; the source line shows the result.\n\n")
	b.WriteString("set my_mailforge_counts = `mailforge sidebar counts`\n")
	fmt.Fprintf(&b, "source %s\n", CountsPath(c))
	return b.String()
}

/*
sidebarHighlight walks the highlight back to the row the fold was pressed on.

Registering mailboxes SCROLLS the sidebar so the open mailbox is the first visible row. Measured in
a real client, not inferred: pressing Enter on the ninth row left that row at the top with the eight
above it off screen and empty space below — and re-sourcing an IDENTICAL list does the same, so this
is the act of registering and not anything about what changed.

NeoMutt offers no way to set the scroll, so the position is rebuilt from the one anchor it does
offer: <sidebar-first> goes to the top of the list, and one <sidebar-next> per row walks back down.
A push rather than a key sequence in the macro, because the number of steps is not a constant — it
depends on which accounts are unfolded above this one, which is exactly what the file being written
knows and a fixed macro cannot.

Zero rows means no account to go back to — a first run, or a state naming an account that is gone —
and then nothing is pushed, because <sidebar-first> alone would be a highlight moved for no reason.
*/
func sidebarHighlight(row int) string {
	if row < 1 {
		return ""
	}
	var b strings.Builder
	b.WriteString("\n# Registering mailboxes scrolls the open one to the top of the sidebar, so the\n")
	b.WriteString("# highlight is walked back to the row this fold was pressed on.\n")
	b.WriteString(`push "<sidebar-first>`)
	for i := 1; i < row; i++ {
		b.WriteString("<sidebar-next>")
	}
	b.WriteString("\"\n")
	return b.String()
}

/*
SidebarToggle is the macro Enter answers to: open the highlighted row, then fold what that turned
out to be.

<sidebar-open> FIRST, and it is the whole reason this acts on the row the user is looking at.
Nothing outside NeoMutt can see which row is highlighted — no function reports it and no expando
carries it — so the only way to act on that row is to open it and then ask what is now open. The
folder-hook answers that, because opening a folder is exactly when it fires.

The first version had no <sidebar-open> and folded whatever account was already open, which on a
freshly started NeoMutt is the default account: Enter folded the top of the list however far down
the highlight had moved. That was not a bug in the state or in the key. It was the wrong question
asked of the only thing that could answer.

Folding is per account and nothing here changes that: this toggles the one row it was pressed on and
leaves every other fold where it was, so several accounts can be open at once and stay that way.

The shell command takes NO account name. It cannot: a macro is fixed text, so the string bound to
Enter is one string for every account and every row.

<check-stats> at the end is not decoration. The mailboxes registered a moment earlier have no counts
yet, so without it an account unfolds with nothing beside its folders until the next check comes
round, and the fold looks like it lost the numbers.
*/
func SidebarToggle(c config.Config) string {
	return "<sidebar-open><shell-escape>mailforge sidebar toggle<enter>" +
		"<enter-command>source " + SidebarPath(c) + "<enter><check-stats>"
}

// InboxHookPath is the file the INBOX folder-hook sources.
func InboxHookPath(c config.Config) string {
	return filepath.Join(c.NeomuttDir, "mailforge", "inbox-hook.rc")
}

/*
InboxHookRC is one line, and it exists because of where a backtick is allowed to run.

A folder-hook whose command contains a backtick does not work for this: NeoMutt expands the backtick
when it PARSES the hook, not when the hook fires, so the command would run once at startup and never
again. Measured, not assumed — a hook command of `touch somefile` left the file behind after a plain
`neomutt -Q`, with the hook never having matched anything.

What does run at the right moment is a file: `folder-hook <pattern> source <file>` re-reads the file
each time the hook fires, and a backtick inside THAT is evaluated then. The account rcs have always
relied on this, which is also why it is trustworthy here.

So: one shared file for every account, because the question it answers has no account in it. Is the
folder that was just opened an INBOX — that is, is it an account's own row in the folded sidebar, or
one of the folders under it?
*/
func InboxHookRC(c config.Config) string {
	var b strings.Builder
	b.WriteString(HeaderFromConfig)
	b.WriteString("#\n")
	b.WriteString("# Sourced by a folder-hook for every path ending in /INBOX, so that Enter can\n")
	b.WriteString("# tell an account's own row from a folder underneath it.\n\n")
	fmt.Fprintf(&b, "set my_mailforge_inbox = `mailforge sidebar inbox`\n")
	return b.String()
}
